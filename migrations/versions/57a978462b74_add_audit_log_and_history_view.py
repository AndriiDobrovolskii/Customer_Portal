# US-013-entity-model.md's Indexes Summary: covering index for FR-1's
# filtered, newest-first query. Also load-bearing for the hash-chain
# trigger's own seed query (`ORDER BY occurred_at DESC, id DESC LIMIT 1`,
# run on every single INSERT) — without this, that query full-scans and
# sorts the table on every write, degrading as the chain grows (caught by
# advisor at IMPLEMENTATION review, 2026-09-02, after `\\d+ audit_log`
# showed only the composite PK). A plain (non-`CONCURRENTLY`) index is
# correct here: `audit_log` is a brand-new, empty table at migration time,
# unlike the four pre-existing, actively-written tables T3c indexes.
# Created on the partitioned parent — PostgreSQL propagates a parent index
# to every partition, including `DEFAULT` and any created later.
_CREATE_COVERING_INDEX = """
CREATE INDEX IF NOT EXISTS ix_audit_log_occurred_at_actor_id_event
    ON audit_log (occurred_at DESC, actor_id, event)
"""
